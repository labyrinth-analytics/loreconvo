"""Hermes tool-schema loader for LoreConvo.

Loads Hermes-format tool schemas from a JSON file generated by
``scripts/build_hermes_tool_schemas.py`` at build time.  The JSON is the
single source of truth for Hermes tool names, descriptions, and parameter
schemas -- derived from the FastMCP server's tool registry, not hand-written.

Filters by the shared tool-group config so Hermes sees the same enabled/
disabled tool set as the MCP server.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

_SCHEMA_FILE = Path(__file__).resolve().parent / "hermes_tool_schemas.json"

# Pro-only tool names (must match server.py gating).
# Derived from grep 'is_pro' ron_skills/loreconvo/src/server.py lines 1018, 1207, 1682, 1727.
_PRO_ONLY_TOOLS: set[str] = {
    "export_for_anthropic",
    "get_docs_for_session",
    "get_related_sessions",
    "rebuild_index",
    "rebuild_index_status",
    "vault_suggest",
    "session_link_doc",
    "inject_agent_context",
}


def load_all_schemas() -> List[Dict[str, Any]]:
    """Return all tool schemas from the JSON file (no group filtering)."""
    if not _SCHEMA_FILE.exists():
        logger.warning("hermes_tool_schemas.json not found -- run build_hermes_tool_schemas.py")
        return []
    data = json.loads(_SCHEMA_FILE.read_text(encoding="utf-8"))
    return data.get("tools", [])


def load_schemas_for_groups(enabled_groups: set) -> List[Dict[str, Any]]:
    """Return tool schemas filtered to *enabled_groups*.

    Uses tool_groups.py for the group assignment.  ALWAYS_ON tools are always
    included.  Raises nothing -- a tool with no group assignment is skipped
    with a warning.
    """
    try:
        from loreconvo.core.tool_groups import TOOL_GROUPS, ALWAYS_ON, classify_tool
    except ImportError:
        logger.warning("tool_groups import failed -- returning all schemas unfiltered")
        return load_all_schemas()

    all_schemas = load_all_schemas()
    result = []
    for schema in all_schemas:
        name = schema.get("name", "")
        if name in ALWAYS_ON:
            result.append(schema)
            continue
        try:
            group = classify_tool(name)
        except (KeyError, ValueError):
            logger.debug("tool %s has no group assignment -- skipping", name)
            continue
        if group in enabled_groups:
            result.append(schema)
    return result


def is_pro_tool(tool_name: str) -> bool:
    """Return True if *tool_name* requires a Pro license."""
    return tool_name in _PRO_ONLY_TOOLS


def upgrade_message() -> str:
    """Return the standard 'upgrade to Pro' message matching MCP server output."""
    return json.dumps({
        "error": "Pro license required.",
        "upgrade_url": "https://buy.stripe.com/9B65kv1VOgk3ekr7VD7N600",
        "note": "Set LORECONVO_PRO=<your-license-key> in plugin.yaml env and restart.",
    })